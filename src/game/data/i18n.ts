export const dictionaries: Record<Language, Record<string, string>> = { fa, en };

let currentLang: Language = 'fa';

export function setLanguage(lang: Language) {
  currentLang = lang;
}

export function getLanguage(): Language {
  return currentLang;
}

export function t(key: string, ...args: (string | number)[]): string {
  let text = dictionaries[currentLang][key] ?? dictionaries.fa[key] ?? key;
  args.forEach((arg, i) => {
    text = text.replace(`{${i}}`, String(arg));
  });
  return text;
}

const FA_DIGITS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];

/** تبدیل اعداد به فارسی */
export function faNum(n: number | string): string {
  const s = typeof n === 'number' ? String(Math.round(n)) : n;
  if (currentLang !== 'fa') return s;
  return s.replace(/[0-9]/g, (d) => FA_DIGITS[Number(d)]);
}
